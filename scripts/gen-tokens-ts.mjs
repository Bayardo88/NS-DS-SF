#!/usr/bin/env node
// Generates src/tokens/generated.ts from tokens/tokens.json.
//
// Every token becomes its CSS reference (`var(--ns-…)`), keyed by its DTCG path, so
// TS code reads `tokens.color.bg.brand` and gets the themed custom property. Values are
// never inlined: themes switch in CSS, not in JS.
//
// `primitives` and `palette` are deliberately left out of the TS API: components use
// semantic tokens only (AI-GUIDE R1). Brand palettes are still in tokens.css for sub-brand pages.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const json = JSON.parse(readFileSync(join(root, 'tokens/tokens.json'), 'utf8'));
const EXCLUDED = new Set(['primitives', 'palette']);

const cssName = (token) => {
  const web = token.$extensions?.['com.figma']?.codeSyntax?.WEB;
  if (web) return web.match(/var\((--[^)]+)\)/)[1];
  return token.$extensions?.['com.nicasource.css']?.customProperty ?? null;
};

const textClasses = [];
function walk(node, path) {
  if (node && typeof node === 'object' && '$type' in node) {
    if (path[0] === 'text-style') {
      const cls = node.$extensions?.['com.nicasource.css']?.className;
      if (cls) textClasses.push(cls);
      return cls ?? undefined;
    }
    const name = cssName(node);
    if (!name) throw new Error(`No CSS name for token ${path.join('.')}`);
    return `var(${name})`;
  }
  const out = {};
  for (const [k, v] of Object.entries(node)) {
    if (k.startsWith('$')) continue;
    const r = walk(v, [...path, k]);
    if (r !== undefined) out[k] = r;
  }
  return out;
}

const tokens = {};
for (const [group, value] of Object.entries(json)) {
  if (group.startsWith('$') || EXCLUDED.has(group) || group === 'text-style') continue;
  tokens[group] = walk(value, [group]);
}
walk(json['text-style'], ['text-style']);

const out = `/* eslint-disable */
// Generated by scripts/gen-tokens-ts.mjs from tokens/tokens.json. Do not edit by hand.

/** Every semantic and scale token as its CSS custom-property reference. Themes switch in CSS. */
export const tokens = ${JSON.stringify(tokens, null, 2)} as const;

/** Class names of the ${textClasses.length} Figma text styles (tokens/css/text-styles.css). */
export const textStyles = ${JSON.stringify(textClasses, null, 2)} as const;

export type Tokens = typeof tokens;
export type TextStyle = (typeof textStyles)[number];
`;
mkdirSync(join(root, 'src/tokens'), { recursive: true });
writeFileSync(join(root, 'src/tokens/generated.ts'), out);
console.log(`src/tokens/generated.ts: ${Object.keys(tokens).length} groups, ${textClasses.length} text styles`);
