#!/usr/bin/env node
/**
 * Regenerates src/icons/generated.ts from the SVGs exported from the Figma "Icons" page.
 * No dependencies (Node 18+).
 *
 *   src/icons/svg/<name>.svg     one file per icon, 24 × 24 viewBox (Figma: Icons/<Category>/<name>)
 *   src/icons/categories.json    { "<name>": "<Category>" } in Figma page order (the source of truth
 *                                for which icons exist and their order)
 *
 * Every SVG is normalized so it draws with currentColor: the outer <svg>, ids, width/height and
 * Figma clutter are stripped, and any fill/stroke color other than none/currentColor becomes
 * currentColor (icons are single-color; Figma binds them to icon/primary).
 *
 * Usage: node scripts/gen-icons.mjs
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const iconsDir = join(root, 'src/icons');
const svgDir = join(iconsDir, 'svg');
const outFile = join(iconsDir, 'generated.ts');
const VIEWBOX = '0 0 24 24';

const categories = JSON.parse(readFileSync(join(iconsDir, 'categories.json'), 'utf8'));
const names = Object.keys(categories);

/** Returns the inner markup of an icon SVG, normalized to currentColor. */
function normalize(name, svg) {
  const open = svg.match(/<svg\b[^>]*>/i);
  if (!open) throw new Error(`${name}.svg: no <svg> element`);
  const viewBox = open[0].match(/viewBox="([^"]+)"/i)?.[1];
  if (viewBox && viewBox.trim() !== VIEWBOX) {
    throw new Error(`${name}.svg: viewBox "${viewBox}" is not "${VIEWBOX}"; the Icon component assumes 24 × 24`);
  }
  return svg
    .slice(open.index + open[0].length, svg.lastIndexOf('</svg>'))
    .replace(/<\?xml[^>]*>|<!--[\s\S]*?-->|<title>[\s\S]*?<\/title>|<desc>[\s\S]*?<\/desc>/gi, '')
    .replace(/\s(?:id|data-[\w-]+|xmlns(?::\w+)?|width|height)="[^"]*"/gi, '')
    .replace(/\s(fill|stroke)="(?!none"|currentColor")[^"]*"/gi, ' $1="currentColor"')
    .replace(/>\s+</g, '><')
    .replace(/\s+/g, ' ')
    .trim();
}

const missing = names.filter((name) => !existsSync(join(svgDir, `${name}.svg`)));
if (missing.length) {
  console.error(`gen-icons: missing SVGs in src/icons/svg: ${missing.join(', ')}`);
  process.exit(1);
}

const svgs = Object.fromEntries(
  names.map((name) => [name, normalize(name, readFileSync(join(svgDir, `${name}.svg`), 'utf8'))]),
);

const out = `/* eslint-disable */
// GENERATED by scripts/gen-icons.mjs from src/icons/svg/*.svg and src/icons/categories.json.
// Do not edit by hand: re-export the SVGs from the Figma "Icons" page and run \`npm run gen:icons\`.

/** Every icon in the Figma Icons page, by its Figma layer name. */
export const iconNames = ${JSON.stringify(names)} as const;
export type IconName = (typeof iconNames)[number];

/** Figma category of each icon (Icons/<Category>/<name>). */
export const iconCategories: Record<IconName, string> = ${JSON.stringify(categories)};

/** Inner SVG markup of each icon, drawn on a 24×24 viewBox with currentColor. */
export const iconSvgs: Record<IconName, string> = ${JSON.stringify(svgs, null, 0)};
`;

writeFileSync(outFile, out);
console.log(`gen-icons: wrote ${names.length} icons to ${outFile.slice(root.length + 1)}`);
